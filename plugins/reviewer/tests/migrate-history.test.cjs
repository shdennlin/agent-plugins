// node --test plugins/reviewer/tests/migrate-history.test.cjs — scripts/migrate-history.cjs (v1 → v2 behind --dry-run)
'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { spawnSync } = require('child_process')
const { validateHistoryRow } = require('../mcp/schema.cjs')

const SCRIPT = path.join(__dirname, '..', 'scripts', 'migrate-history.cjs')
const FIXTURE = path.join(__dirname, 'fixtures', 'history-v1.jsonl')
const tmpCopy = () => { const d = fs.mkdtempSync(path.join(os.tmpdir(), 'mig-')); const f = path.join(d, 'history.jsonl'); fs.copyFileSync(FIXTURE, f); return f }
const run = (args) => spawnSync('node', [SCRIPT, ...args], { encoding: 'utf8' })
const rows = (f) => fs.readFileSync(f, 'utf8').trim().split('\n').map((l) => JSON.parse(l))

test('dry-run leaves the file byte-identical and prints the summary', () => {
  const f = tmpCopy(); const before = fs.readFileSync(f)
  const r = run([f, '--dry-run'])
  assert.equal(r.status, 1, 'exit 1 because two rows are unmigratable')
  assert.ok(before.equals(fs.readFileSync(f)))
  assert.match(r.stdout, /rows: 15, migrated: 12 \(v1→v3: 9, v2→v3: 3\), already-v3: 1/)
  assert.match(r.stdout, /engine '' → claude: 3/); assert.match(r.stdout, /claude-result → claude: 1/); assert.match(r.stdout, /both → engines: 1 \(second engine: unknown\)/)
  assert.match(r.stdout, /round→int: 9/); assert.match(r.stdout, /change normalized: 2/); assert.match(r.stdout, /unmigratable: 2/)
  assert.match(r.stderr, /line 8:.*severity/); assert.match(r.stderr, /line 9:.*title/)
  assert.ok(!fs.existsSync(f + '.v1.bak'))
})
test('a real run writes the backup, rewrites the rows, and every migrated row validates', () => {
  const f = tmpCopy(); const before = fs.readFileSync(f)
  const r = run([f, '--second-engine', 'spectra-review'])
  assert.equal(r.status, 1)
  assert.ok(before.equals(fs.readFileSync(f + '.v1.bak')), 'backup is the original')
  const rs = rows(f); assert.equal(rs.length, 15)
  const migrated = rs.filter((x) => x.v === 3)
  assert.equal(migrated.length, 13)
  for (const x of migrated) assert.deepEqual(validateHistoryRow(x), [], JSON.stringify(x))
  assert.equal(rs[0].engine, 'claude'); assert.equal(rs[0].round, 1); assert.equal(rs[0].change, 'openspec/changes/a'); assert.deepEqual(rs[0].locations, [{ path: 'proposal.md' }]); assert.equal(rs[0].pattern, null); assert.equal(rs[0].run_id, null); assert.equal(rs[0].outcome, 'unknown')
  assert.equal(rs[2].engine, 'claude'); assert.equal(rs[2].change, 'openspec/changes/b'); assert.deepEqual(rs[2].locations, [{ path: 'src/y.py', symbol: 'parse' }, { path: 'src/z.py', symbol: 'load' }])
  assert.equal(rs[3].engine, 'claude'); assert.deepEqual(rs[3].engines, ['claude', 'spectra-review'])
  assert.equal(rs[5].engine, 'codex'); assert.deepEqual(rs[5].engines, ['codex'])
  assert.equal(rs[6].engine, 'spectra-review')
  assert.equal(rs[11].engine, 'code-review')
  assert.equal(rs[9].v, 3); assert.equal(rs[9].outcome, 'unknown'); assert.deepEqual(rs[9].locations, [{ path: 'a.py', symbol: 'f' }], 'a v2 row gains outcome unknown and parsed locations')
  assert.deepEqual(JSON.parse(fs.readFileSync(FIXTURE, 'utf8').trim().split('\n')[14]), rs[14], 'an already-v3 row is kept verbatim')
  assert.deepEqual(JSON.parse(fs.readFileSync(FIXTURE, 'utf8').trim().split('\n')[7]), rs[7], 'an unmigratable row is kept verbatim')
  assert.match(r.stdout, /second engine: spectra-review/)
})
test('both without --second-engine gives engines [claude] and a stderr count', () => {
  const f = tmpCopy(); const r = run([f])
  assert.deepEqual(rows(f)[3].engines, ['claude'])
  assert.match(r.stderr, /1 'both' row\(s\) kept engines \[claude\]: pass --second-engine/)
})
test('an existing .v1.bak refuses to run', () => {
  const f = tmpCopy(); fs.writeFileSync(f + '.v1.bak', 'x')
  const r = run([f]); assert.equal(r.status, 1); assert.match(r.stderr, /\.v1\.bak already exists/)
  assert.equal(fs.readFileSync(f + '.v1.bak', 'utf8'), 'x')
})
test('a clean v1 file exits 0', () => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), 'mig-')); const f = path.join(d, 'h.jsonl')
  fs.writeFileSync(f, fs.readFileSync(FIXTURE, 'utf8').trim().split('\n').filter((_, i) => i !== 7 && i !== 8).join('\n') + '\n')
  const r = run([f, '--dry-run']); assert.equal(r.status, 0, r.stderr); assert.match(r.stdout, /unmigratable: 0/)
})
