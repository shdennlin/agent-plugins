#!/usr/bin/env bash
# Consistency checks for the explain command, skill, agents and README: the few statements that
# must agree across files and that a prompt edit can silently break. Text checks only; they do
# not run any model.
#
#   bash plugins/digest/tests/explain-docs.test.sh
set -euo pipefail

D="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CMD="$D/commands/explain.md"
SKILL="$D/skills/explain/SKILL.md"
AGENT="$D/agents/explain-agent.md"
CODEX="$D/skills/explain/explain-agent.md"
README="$D/README.md"
SCRIPT="$D/scripts/classify-target.sh"

fail() { echo "ASSERT FAIL: $*" >&2; exit 1; }

# 1. The heredoc that feeds the script uses a terminator no user text will contain: a bare ARGS
#    line in a multi-line argument would otherwise end it early and run the rest in the shell.
grep -n "^ARGS$\|<<'ARGS'" "$CMD" "$SCRIPT" && fail "bare ARGS heredoc terminator still present"
grep -q "<<'DIGEST_EXPLAIN_ARGS_9f3a'" "$CMD" || fail "command must use the unique heredoc terminator"

# 3. The PR number handed to gh has no '#': in a shell, '#42' starts a comment and gh would show the
#    current branch's PR instead.
for f in "$AGENT" "$CODEX"; do
  grep -q 'without the `#`' "$f" || fail "$f must say the gh PR number has no #"
done

# 4. Card mode writes no file, so the Claude agent's Behavior must not write the HTML unconditionally.
grep -q 'When Output mode is `html`, write to' "$AGENT" || fail "agent Behavior must scope the file write to html mode"

# 5. The command stops, with a message, when a branch target has nothing to compare.
grep -q 'has no changes against' "$CMD" || fail "command needs the no-changes stop for a branch target"
grep -q 'No base branch' "$CMD" || fail "command needs the no-base stop for a branch target"

# 6. The migration note admits that tags, short hashes and HEAD~n are no longer branches.
grep -q -- '--as branch' "$README" || fail "README migration note must mention --as branch"
grep -q -- '-e` / `--export' "$README" || grep -q -- '`-e`' "$README" || fail "README must mention the -e error"

# 7. HTML is the default for every target and --print is the way to get the answer in chat: the
#    old card-default wording must be gone and every file must know --print.
for f in "$CMD" "$SKILL" "$README" "$SCRIPT"; do
  grep -q -- '--print' "$f" || fail "$f must document --print"
done
grep -n -i -E 'card in chat|chat card|unless `html`' "$CMD" "$SKILL" "$README" "$SCRIPT" "$AGENT" "$CODEX" \
  && fail "a file still says change targets default to a chat card"
grep -n 'card | html' "$CMD" "$SKILL" "$AGENT" "$CODEX" && fail "Output mode must be html | print, not card | html"
for f in "$CMD" "$SKILL" "$AGENT" "$CODEX"; do
  grep -q 'html | print\|html` or `print\|`print`' "$f" || fail "$f must name the print output mode"
done

# 8. Every flag's short form is documented where the flags are listed.
for s in '-t, --teach' '-p, --print' '-a, --as'; do
  grep -q -- "$s" "$SCRIPT" || fail "$SCRIPT must list '$s'"
done
for s in '-t|--teach' '-p|--print' '-a|--as'; do
  for f in "$CMD" "$README"; do
    grep -q -F -- "$s" "$f" || fail "$f must list '$s' in the usage line"
  done
done

# 9. --html / -H were removed: no file may list or praise them, and the README migration says why.
grep -n -F -e '-H, --html' -e '-H|--html' "$CMD" "$SKILL" "$README" && fail "a file still lists the removed --html / -H flag"
grep -n -i -E 'html. is accepted|--html. also works|accepted so 2\.x|means the same' "$CMD" "$SKILL" "$README" "$SCRIPT" \
  && fail "a file still says --html is accepted"
grep -q 'HTML is already the default' "$README" || fail "README migration must say HTML is already the default"

# 10. The HTML template is the C3 spec: constraints, content floor, a concrete avoid list, free form,
#     and it says the result is checked by the script.
TEMPLATE="$D/templates/html-explainer.md"
for needle in 'Expand all' 'Where to focus' 'Risk per file' 'check-explainer.sh' 'Everything else is yours'; do
  grep -q -F -- "$needle" "$TEMPLATE" || fail "template must contain '$needle'"
done
# The avoid list gives concrete examples of a card inside a card, not just the rule.
grep -q -i 'number tiles' "$TEMPLATE" || fail "template must name number tiles as a card inside a card"
grep -q -i 'inside a `<details>`' "$TEMPLATE" || fail "template must name a box inside a <details> as a card inside a card"
# The old prescriptions it replaces must be gone: the accent-stripe diffstat strip, the fixed skeleton, the footer label.
grep -n -i -E 'left border|generated by digest|class="hero"|filerow' "$TEMPLATE" && fail "template still prescribes the old skeleton or accent stripe"
[[ "$(wc -l <"$TEMPLATE" | tr -d ' ')" -lt 80 ]] || fail "template should stay short (under 80 lines)"

# 11. Whoever writes an HTML file must run the checker and fix what it reports.
for f in "$AGENT" "$CODEX" "$CMD" "$SKILL"; do
  grep -q 'check-explainer.sh' "$f" || fail "$f must tell the writer to run check-explainer.sh"
done
for f in "$AGENT" "$CODEX"; do
  grep -q -i 'fix' "$f" && grep -q -- '--numstat' "$f" || fail "$f must say to fix what the checker reports and pass --numstat for change targets"
done

# 12. Version 3.1.0 in both manifests, and the README admits the python3 dependency.
[[ "$(jq -r .version "$D/.claude-plugin/plugin.json")" == "3.1.0" ]] || fail "plugin.json must be 3.1.0"
[[ "$(jq -r '.plugins[] | select(.name=="digest") | .version' "$D/../../.claude-plugin/marketplace.json")" == "3.1.0" ]] \
  || fail "marketplace.json digest entry must be 3.1.0"
grep -q 'python3' "$README" || fail "README must name python3 as a requirement of the checker"
grep -q 'check-explainer' "$README" || fail "README must mention the explainer checker"

# 13. SKILL.md stays a slim Codex entry point: the flags have one list (the script's --help), the
#     always-loaded description is short, and what only Codex needs (Process, Teach mode) is still there.
[[ "$(wc -c <"$SKILL" | tr -d ' ')" -lt 4800 ]] || fail "SKILL.md should stay under 4800 bytes, it is $(wc -c <"$SKILL" | tr -d ' ')"
desc_len="$(sed -n '/^description:/p' "$SKILL" | head -1 | wc -c | tr -d ' ')"
[[ "$desc_len" -lt 330 ]] || fail "SKILL.md description should stay under 330 characters, it is $desc_len"
[[ "$(grep -c '^| `-' "$SKILL" || true)" == "0" ]] || fail "SKILL.md must not carry its own flag table"
grep -q 'classify-target.sh --help' "$SKILL" || fail "SKILL.md must point to classify-target.sh --help as the list of flags"
grep -q '^## Teach mode' "$SKILL" && grep -q '^## Process' "$SKILL" || fail "SKILL.md must keep its Process and Teach mode sections"
sed -n '/^description:/p' "$SKILL" | head -1 | grep -q -i 'branch' && sed -n '/^description:/p' "$SKILL" | head -1 | grep -q -i 'PR' \
  || fail "the description must still name branch and PR so the skill triggers on them"

# 14. The narrow-window rule says how to fit (own scrolling container, no hidden overflow on the page, whole
#     words in table cells) and the template covers diagram labels, which the checker cannot verify.
grep -q 'overflow-x: auto' "$TEMPLATE" || fail "template must say wide content sits in an overflow-x: auto container"
grep -q -i 'never put `overflow: hidden`' "$TEMPLATE" || fail "template must forbid overflow hidden on html and body"
grep -q -i 'keep their words whole' "$TEMPLATE" || fail "template must say table cells keep their words whole"
grep -q -i 'clear of every line' "$TEMPLATE" || fail "template must say diagram labels stay clear of every line"

# 15. A forked explain must follow the whole agent prompt, including the checking step. A hand-written list
#     of sections goes stale the moment a section is added, so the fork prompt says "everything below".
grep -n -E 'follow its Input, Behavior' "$CMD" && fail "the fork prompt lists agent sections by name; it must say everything below the frontmatter"
grep -q 'everything below its frontmatter' "$CMD" || fail "the fork prompt must tell the fork to follow everything below the agent's frontmatter"

# 16. Prompt wording that came out of review of generated pages: risk only for a change, a diagram must earn
#     its place, and inline code has to be allowed to wrap on a phone.
grep -q -i 'for a change, how risky' "$TEMPLATE" || fail "rule 4 must ask for risk only for a change"
grep -q -i 'earns its place' "$TEMPLATE" || fail "template must say a diagram earns its place"
grep -q -i 'inline `code`' "$TEMPLATE" && grep -q -i 'allowed to wrap' "$TEMPLATE" || fail "template must say long paths and inline code are allowed to wrap"

# 17. The template says what color, highlight and evidence grades mean, what every page must contain, and
#     that the language defaults to English; the checker and the render check are named where they are used.
for needle in '`--ok`' '<mark>' 'weakest link' 'What I did not verify' 'How to verify' 'jump links' ':focus-visible' \
              'color-scheme' 'English unless' 'tabular-nums' 'text-wrap' 'check-render.sh' '`measured`' '`inferred`'; do
  grep -q -F -- "$needle" "$TEMPLATE" || fail "template must contain '$needle'"
done
[[ "$(wc -l <"$TEMPLATE" | tr -d ' ')" -lt 80 ]] || fail "template should stay under 80 lines, it has $(wc -l <"$TEMPLATE" | tr -d ' ')"
for f in "$AGENT" "$CODEX"; do
  grep -q 'check-render.sh' "$f" || fail "$f must mention the optional render check"
  grep -q 'English unless' "$f" || fail "$f must say pages are in English unless the user asked otherwise"
  grep -q '`measured`' "$f" || fail "$f must ask for evidence grades"
done
grep -q 'check-render.sh' "$CMD" || fail "the command must pass on and mention the render checker"
grep -q 'check-render.sh' "$SKILL" || fail "SKILL.md must mention the render checker"
grep -q 'check-render.sh' "$README" && grep -q -i 'chrome' "$README" || fail "README must mention the render check and that Chrome is optional"

echo "ok: explain-docs"
